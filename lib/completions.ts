import { dateStyles, hourCycles, timeStyles } from "./common.ts";
import {
  localPartTypes,
  templateKeywordDescriptions,
  templateKeywords,
} from "./renderDateTemplate.ts";
import { makeFlags } from "../makeFlags.ts";

export const completionShells = ["bash", "zsh", "fish"] as const;
export type CompletionShell = (typeof completionShells)[number];

export const isCompletionShell = (value: unknown): value is CompletionShell =>
  completionShells.includes(value as CompletionShell);

const completionDescription = "print the shell completion script";

// Everything below is generated from the same sources the CLI uses (the flag
// rules of makeFlags.ts and the template properties of renderDateTemplate.ts),
// so the completions cannot drift from the real options.

const flagRules = () => makeFlags([]).optionsHelp;

const shortDescription = (description = "") =>
  description.replace(/\.$/, "").replace(/^([A-Z])(?=[a-z])/, (c) =>
    c.toLowerCase());

const sq = (text: string) => text.replaceAll("'", `'\\''`);

/** Template properties with their description, e.g. `YYYY`, `local_year`. */
const templateProperties = (): [string, string][] => [
  ...templateKeywords.map((keyword): [string, string] => [
    keyword,
    shortDescription(templateKeywordDescriptions[keyword]),
  ]),
  ...localPartTypes.map((part): [string, string] => [
    `local_${part}`,
    `"${part}" part of Intl.DateTimeFormat`,
  ]),
];

const bashScript = () => {
  const options = flagRules().flatMap(({ names }) => names);
  const words = (list: readonly string[]) => list.join(" ");
  return `# bash completion for ndate
#
# Generated by \`ndate completion bash\`. Install:
#   source <(ndate completion bash)
# or save it in your bash-completion directory, e.g.
#   ndate completion bash > "$(brew --prefix)/etc/bash_completion.d/ndate"
#   ndate completion bash > ~/.local/share/bash-completion/completions/ndate

_ndate_time_zones() {
  local zoneinfo
  for zoneinfo in "\${TZDIR:-}" /usr/share/zoneinfo /usr/lib/zoneinfo /usr/share/lib/zoneinfo; do
    if [[ -n "$zoneinfo" && -d "$zoneinfo" ]]; then
      (cd "$zoneinfo" && find -L . -type f 2>/dev/null) |
        sed -e 's|^\\./||' |
        grep -E '^[A-Z][A-Za-z0-9_+-]*(/[A-Za-z0-9_+-]+)*$' |
        grep -vE '^(posix|right|Etc/Unknown)/|^(Factory|posixrules|SystemV)$'
      return
    fi
  done
}

_ndate_locales() {
  local locales
  locales=$(locale -a 2>/dev/null |
    sed -n -e 's/^\\([a-z][a-z]\\)_\\([A-Z][A-Z]\\).*/\\1-\\2/p' |
    sort -u)
  printf '%s\\n' \${locales:-en-US es-CL es-ES en-GB fr-FR de-DE pt-BR ja-JP}
}

_ndate() {
  local cur prev
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  local opts="${words(options)}"

  if [[ "$prev" == completion && $COMP_CWORD -eq 2 ]]; then
    COMPREPLY=($(compgen -W "${words(completionShells)}" -- "$cur"))
    return 0
  fi

  case "$prev" in
    --date | -d)
      COMPREPLY=($(compgen -W "now" -- "$cur"))
      return 0
      ;;
    --date-style)
      COMPREPLY=($(compgen -W "${words(dateStyles)}" -- "$cur"))
      return 0
      ;;
    --time-style)
      COMPREPLY=($(compgen -W "${words(timeStyles)}" -- "$cur"))
      return 0
      ;;
    --hour-cycles)
      COMPREPLY=($(compgen -W "${words(hourCycles)}" -- "$cur"))
      return 0
      ;;
    --time-zone | -tz)
      COMPREPLY=($(compgen -W "$(_ndate_time_zones)" -- "$cur"))
      return 0
      ;;
    --local | -l)
      COMPREPLY=($(compgen -W "$(_ndate_locales)" -- "$cur"))
      return 0
      ;;
    --template)
      # Free text, e.g. '{{YYYY}}-{{MM}}-{{DD}}'
      return 0
      ;;
  esac

  if [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=($(compgen -W "completion $opts" -- "$cur"))
  else
    COMPREPLY=($(compgen -W "$opts" -- "$cur"))
  fi
  return 0
}

complete -F _ndate ndate
`;
};

const zshValues: Record<string, string> = {
  "--date": "date:(now)",
  "--date-style": `date style:(${dateStyles.join(" ")})`,
  "--time-style": `time style:(${timeStyles.join(" ")})`,
  "--hour-cycles": "hour cycle:((h11\\:\"0-11\" h12\\:\"1-12\" h23\\:\"0-23, 24 hours\" h24\\:\"1-24\" none))",
  "--time-zone": "time zone:_time_zone",
  "--local": "locale:_ndate_locales",
  "--template": "template:_ndate_template_properties",
};

const zshScript = () => {
  const specs = flagRules().flatMap(({ names, description, label }) => {
    if (names[0] === "-") return [`'-[read the date from stdin]'`];
    const text = sq(shortDescription(description));
    const value = label ? `:${zshValues[names[0]] ?? `${names[0].slice(2)}:`}` : "";
    const exclusive = names.length > 1 ? `(${names.join(" ")})` : "";
    const standalone = names[0] === "--help" || names[0] === "--version"
      ? "(- *)"
      : exclusive;
    return [
      names.length > 1
        ? `'${standalone}'{${names.join(",")}}'[${text}]${value}'`
        : `'${standalone}${names[0]}[${text}]${value}'`,
    ];
  });
  const properties = templateProperties()
    .map(([name, description]) => `    '${name}:${sq(description)}'`)
    .join("\n");

  return `#compdef ndate
#
# zsh completion for ndate
#
# Generated by \`ndate completion zsh\`. Install: save it as \`_ndate\` in a
# directory on your $fpath, e.g.
#   mkdir -p ~/.zsh/completions
#   ndate completion zsh > ~/.zsh/completions/_ndate
#   # in ~/.zshrc, before compinit:
#   fpath=(~/.zsh/completions $fpath)
#   autoload -Uz compinit && compinit
# With Homebrew, it can live at "$(brew --prefix)/share/zsh/site-functions/_ndate".

_ndate_locales() {
  local -a locales
  locales=(\${(u)\${(f)"$(locale -a 2>/dev/null | sed -n -e 's/^\\([a-z][a-z]\\)_\\([A-Z][A-Z]\\).*/\\1-\\2/p')"}})
  (( \${#locales} )) || locales=(en-US es-CL es-ES en-GB fr-FR de-DE pt-BR ja-JP)
  _describe -t locales 'locale' locales
}

_ndate_template_properties() {
  local -a properties
  properties=(
${properties}
  )

  # A positional template is written as +<template>, like date +FORMAT.
  compset -P '+'

  # Complete a property after an opening "{{" that is not closed yet.
  if [[ $PREFIX == *'{{'* && \${PREFIX##*'{{'} != *'}}'* ]]; then
    compset -P '*{{'
    _describe -t properties 'template property' properties -S '}}'
  else
    _message -e templates "template, e.g. '{{YYYY}}-{{MM}}-{{DD}}'"
  fi
}

_ndate() {
  # \`ndate completion <shell>\`
  if [[ $words[2] == completion ]]; then
    (( CURRENT == 3 )) && _values 'shell' ${completionShells.join(" ")}
    return
  fi

  if (( CURRENT == 2 )) && [[ $PREFIX != [-+]* ]]; then
    local -a commands=('completion:${completionDescription}')
    _describe -t commands 'command' commands
  fi

  _arguments -S \\
${specs.map((spec) => `    ${spec} \\`).join("\n")}
    '*:+template:_ndate_template_properties'
}

_ndate "$@"
`;
};

const fishScript = () => {
  const lines = flagRules().flatMap(({ names, description, label }) => {
    if (names[0] === "-") return [];
    const forms = names.map((name) =>
      name.startsWith("--")
        ? `-l ${name.slice(2)}`
        : name.length === 2
        ? `-s ${name.slice(1)}`
        : `-o ${name.slice(1)}`
    ).join(" ");
    const values: Record<string, string> = {
      "--date": "now",
      "--date-style": dateStyles.join(" "),
      "--time-style": timeStyles.join(" "),
      "--hour-cycles": hourCycles.join(" "),
      "--time-zone": "(__ndate_time_zones)",
      "--local": "(__ndate_locales)",
    };
    const arg = !label
      ? ""
      : names[0] === "--template"
      ? " -x -a '(__ndate_template_properties)'"
      : ` -x -a '${values[names[0]] ?? ""}'`;
    const text = sq(shortDescription(description));
    return [`complete -c ndate ${forms}${arg} -d '${text}'`];
  });
  const properties = templateProperties()
    .map(([name, description]) => `    echo '{{${name}}}\\t${sq(description)}'`)
    .join("\n");

  return `# fish completion for ndate
#
# Generated by \`ndate completion fish\`. Install:
#   ndate completion fish > ~/.config/fish/completions/ndate.fish
# or load it in the current session:
#   ndate completion fish | source

function __ndate_time_zones
    for zoneinfo in "$TZDIR" /usr/share/zoneinfo /usr/lib/zoneinfo /usr/share/lib/zoneinfo
        if test -n "$zoneinfo" -a -d "$zoneinfo"
            find -L "$zoneinfo" -type f 2>/dev/null | string replace -r '^'(string escape --style=regex "$zoneinfo")'/' '' |
                string match -r '^[A-Z][A-Za-z0-9_+-]*(/[A-Za-z0-9_+-]+)*$' |
                string match -rv '^(posix|right|Etc/Unknown)/|^(Factory|posixrules|SystemV)$'
            return
        end
    end
end

function __ndate_locales
    set -l locales (locale -a 2>/dev/null | string replace -rf '^([a-z]{2})_([A-Z]{2}).*' '$1-$2' | sort -u)
    if test (count $locales) -eq 0
        set locales en-US es-CL es-ES en-GB fr-FR de-DE pt-BR ja-JP
    end
    printf '%s\\n' $locales
end

function __ndate_template_properties
${properties}
end

complete -c ndate -f
complete -c ndate -n '__fish_use_subcommand' -a completion -d '${completionDescription}'
complete -c ndate -n '__fish_seen_subcommand_from completion' -x -a '${completionShells.join(" ")}'
${lines.join("\n")}
`;
};

export const renderCompletion = (shell: CompletionShell): string => {
  switch (shell) {
    case "bash":
      return bashScript();
    case "zsh":
      return zshScript();
    case "fish":
      return fishScript();
  }
};
